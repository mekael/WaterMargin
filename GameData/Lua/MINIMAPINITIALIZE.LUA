G_MiniMapManager = { RunTimeTag = {} , FixedTag = {} }
G_CurrentTime = 0
--=============================================================================
function MiniMapOnTime()
	G_MiniMapManager.RunTimeTag = {}
	while true do
		for i,MiniMap in pairs ( G_MiniMapManager.RunTimeTag ) do
			if MiniMap ~= nil then
				-- 生存時間到時執行移除
				if (G_CurrentTime >  MiniMap.LiveTime) and (MiniMap.LiveTime ~= -1) then
					RemoveMiniMapPic( MiniMap.TagId );
				end
			end
		end
		Sleep(1);
		G_CurrentTime = G_CurrentTime + 1;
	end
end 
--=============================================================================
-- 在小地圖上顯示出現警告標記
function AlterTag_Show_OnMiniMap()
	local GId = TargetID();
	local X,Y,Z = C_GetPositionByNPCGroupId(GId);
	if (X == nil ) then
		return;
	end
	local MapId = GId+10000;
	
	AddMiniMapPic( MapId , 57 , X , Y , Z , -1 );
	
	--設定指南針
	L_CompassShow();
	L_SetCompassDestination(X , Y , Z );
end
--=============================================================================
-- 關閉小地圖上警告標記
function AlterTag_Close_OnMiniMap()
	local GId = TargetID();
	RemoveMiniMapPic(GId + 10000);
end
--=============================================================================
-- 加入需要被Script 控制的小地圖
function AddMiniMapPic ( TagId , GfxId , vX,vY,vZ , LiveTime )
	C_AddMiniMapPic(TagId, GfxId ,-1,vX,vY,vZ);
	G_MiniMapManager.RunTimeTag[TagId] ={};
	G_MiniMapManager.RunTimeTag[TagId].TagId = TagId;
	G_MiniMapManager.RunTimeTag[TagId].Use = true;		-- 增加一個Tag

	if (LiveTime == -1 ) then
		G_MiniMapManager.RunTimeTag[TagId].LiveTime = LiveTime	-- 生存時間無限
	else
		G_MiniMapManager.RunTimeTag[TagId].LiveTime = G_CurrentTime + LiveTime;
	end
	G_MiniMapManager.RunTimeTag[TagId].CurrentTime = G_CurrentTime;
end
--=============================================================================
-- 移除小地圖上的Tag
function RemoveMiniMapPic ( TagId  )
	C_RemoveMiniMapPic(TagId);
	G_MiniMapManager.RunTimeTag[TagId] = nil;
end
--=============================================================================
-- Client 每次換地圖會執行一次
function Client_MiniMap_Initialize_Script()
	All_LevelDesign_FixTag()
	local CurrentLevelDesignId = C_GetCurrnetLevelDesignId()
	local CurrentLevelDesign_Initialize = nil
	if CurrentLevelDesignId > 0 then
		CurrentLevelDesign_Initialize = G_MiniMapManager.FixedTag[CurrentLevelDesignId]
		if ( nil == CurrentLevelDesign_Initialize ) then
			return
		end
	else
		return
	end

	-- 加入小地圖
	if type( CurrentLevelDesign_Initialize ) == "table" then
		for i,v in pairs ( CurrentLevelDesign_Initialize ) do
			local TagId,vX,vY,vZ,nStrngId,nGfxId
			TagId 		= i
			nGfxId		= v[1]
			nStrngId	= v[2]
			vX			= v[3]
			vY			= v[4]
			vZ			= v[5]
			C_AddMiniMapPic ( TagId , nGfxId , nStrngId , vX , vY , vZ)
		end
	end
end
